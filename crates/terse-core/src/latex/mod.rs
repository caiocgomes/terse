//! LaTeX generation for the milestone-2 semantic subset (metadata, inline
//! markup, headings, paragraphs). No implicit dates, no absolute paths, no
//! timestamps: same module always produces the same bytes.

pub mod bibliography;
pub mod escape;
pub mod source_map;

use crate::semantic::{
    build_symbol_table, has_bibliography, Citation, CiteItem, DocumentMetadata, ListItem, Node, NodeKind,
    ParsedModule, SymbolKind, SymbolTable, TheoremKind,
};
