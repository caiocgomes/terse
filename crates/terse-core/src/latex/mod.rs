#[cfg(test)]
mod tests {
    use super::*;
    use crate::semantic::{Author, Node, NodeKind};
    use crate::source::{FileId, SourceSpan};
    use crate::theme;

    fn span() -> SourceSpan {
        SourceSpan::new(FileId(0), 0, 0)
    }

    #[test]
    fn test_generate_document_is_deterministic_and_untimestamped() {
        let module = ParsedModule {
            file_id: FileId(0),
            metadata: Some(DocumentMetadata {
                title: "A Paper".to_string(),
                subtitle: None,
                authors: vec![Author {
                    name: "Ada Lovelace".to_string(),
                    affiliation: None,
                }],
                affiliations: vec![],
                date: None,
                language: "en".to_string(),
                abstract_blocks: vec![],
                keywords: vec![],
            }),
            references: vec![],
            blocks: vec![
                Node {
                    kind: NodeKind::Heading {
                        level: 1,
                        id: None,
                        inlines: vec![Inline::Text("Intro".to_string())],
                    },
                    span: span(),
                },
                Node {
                    kind: NodeKind::Paragraph {
                        inlines: vec![Inline::Text("50% done & counting.".to_string())],
                    },
                    span: span(),
                },
            ],
        };
        let theme = theme::academic();
        let out1 = generate_document(&module, &theme);
        let out2 = generate_document(&module, &theme);
        assert_eq!(out1, out2);
        assert!(out1.contains("\\TerseTitle{A Paper}"));
        assert!(out1.contains("\\TerseAuthor{Ada Lovelace}"));
        assert!(out1.contains("\\TerseHeadingOne{Intro}"));
        assert!(out1.contains("50\\% done \\& counting."));
        assert!(!out1.contains("\\today"));
    }
}
